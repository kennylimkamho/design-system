// Minimal DTCG-style token compiler.
//
// Reads ./src/{primitives,semantic}/*.json, resolves {ref} aliases,
// emits ./dist/tokens.css (light + dark CSS variables) and ./dist/tokens.json.
//
// Usage:  pnpm --filter @design-system/tokens build

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'src');
const outDir = join(here, 'dist');

// ---------- collect all token files ----------
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) files.push(...(await walk(full)));
    else if (e.name.endsWith('.json')) files.push(full);
  }
  return files;
}

const files = await walk(srcDir);
const tokens = {};
for (const f of files) {
  const json = JSON.parse(await readFile(f, 'utf8'));
  mergeDeep(tokens, json);
}

function mergeDeep(target, source) {
  for (const [k, v] of Object.entries(source)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && !('$value' in v)) {
      target[k] ??= {};
      mergeDeep(target[k], v);
    } else {
      target[k] = v;
    }
  }
}

// ---------- resolve {ref} aliases into a flat Map of leaf entries ----------
// Key = dot-path, value = the final primitive string.
function getByPath(obj, path) {
  // Walk into the merged tree, returning the $value string when we hit a leaf.
  const parts = path.split('.');
  let cur = obj;
  for (const p of parts) {
    if (cur == null) return undefined;
    cur = cur[p];
  }
  if (cur && typeof cur === 'object' && '$value' in cur) {
    return cur.$value;
  }
  return cur;
}

function resolveValue(raw, seen = new Set()) {
  if (typeof raw !== 'string') return raw;
  const m = raw.match(/^\{([^}]+)\}$/);
  if (!m) return raw;
  if (seen.has(m[1])) return raw; // cycle guard
  seen.add(m[1]);
  const next = getByPath(tokens, m[1]);
  return typeof next === 'string' ? resolveValue(next, seen) : next;
}

const leaves = new Map();

function walkResolve(node, pathParts = []) {
  if (node === null || typeof node !== 'object') return;
  if (Array.isArray(node)) return;
  if ('$value' in node) {
    leaves.set(pathParts.join('.'), resolveValue(node.$value));
    return;
  }
  for (const [k, v] of Object.entries(node)) {
    walkResolve(v, [...pathParts, k]);
  }
}

walkResolve(tokens);

// ---------- emit CSS (light + dark) ----------
function kebab(s) {
  return s.replace(/[._]/g, '-').toLowerCase();
}

const darkOverrides = new Set([
  'color.bg.canvas',
  'color.bg.surface',
  'color.bg.raised',
  'color.bg.sunken',
  'color.bg.inverse',
  'color.text.primary',
  'color.text.secondary',
  'color.text.tertiary',
  'color.text.onInverse',
  'color.border.subtle',
  'color.border.default',
  'color.border.strong',
]);

const darkValues = {
  'color.bg.canvas': '#0C0A09',
  'color.bg.surface': '#1C1917',
  'color.bg.raised': '#292524',
  'color.bg.sunken': '#0C0A09',
  'color.bg.inverse': '#FAFAFA',
  'color.text.primary': '#FAFAFA',
  'color.text.secondary': '#D6D3D1',
  'color.text.tertiary': '#A8A29E',
  'color.text.onInverse': '#1C1917',
  'color.border.subtle': '#292524',
  'color.border.default': '#44403C',
  'color.border.strong': '#D6D3D1',
};

function emitBlock(themeAttr, isDark) {
  const lines = [];
  for (const [path, value] of leaves.entries()) {
    let val = value;
    if (isDark && darkValues[path]) val = darkValues[path];
    lines.push(`  --${kebab(path)}: ${val};`);
  }
  return [`${themeAttr} {`, ...lines, `}`].join('\n');
}

const css = [
  '/* Auto-generated by packages/tokens/build.mjs — do not edit. */',
  '',
  emitBlock(':root', false),
  '',
  emitBlock('[data-theme="dark"]', true),
  '',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  ...leaves.entries()
    .filter(([p]) => darkOverrides.has(p))
    .map(([p, v]) => `    --${kebab(p)}: ${darkValues[p] ?? v};`),
  '  }',
  '}',
  '',
].join('\n');

// ---------- emit JSON (resolved, nested) ----------
// Reconstruct a nested object from the dot-path leaves for downstream TS consumers.
const resolvedNested = {};
for (const [path, value] of leaves.entries()) {
  const parts = path.split('.');
  let cur = resolvedNested;
  for (let i = 0; i < parts.length - 1; i++) {
    cur[parts[i]] ??= {};
    cur = cur[parts[i]];
  }
  cur[parts[parts.length - 1]] = value;
}

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'tokens.css'), css, 'utf8');
await writeFile(
  join(outDir, 'tokens.json'),
  JSON.stringify(resolvedNested, null, 2) + '\n',
  'utf8',
);

console.log(`tokens: wrote ${leaves.size} tokens to dist/`);